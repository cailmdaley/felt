const (
	// DirName is the directory where felt files are stored.
	DirName = ".felt"
	// FileExt is the extension for felt files.
	FileExt = ".md"
	// LegacyMystConfigName is a MyST project file older felt versions wrote
	// into the store root. felt no longer creates one; the readers skip it so
	// a store that still carries one is read cleanly.
	LegacyMystConfigName = "myst.yml"
	// GitignoreName is the felt store ignore file generated at init time.
	GitignoreName = ".gitignore"
)

const defaultGitignore = `# Generated by felt — local fiber-write locks
*.md.lock
`

// Storage handles reading and writing felt files.
type Storage struct {
	root string // Path to .felt directory

	// quietWalk silences the per-file "failed to parse" and iCloud-eviction
	// warnings the listing walk prints to stderr. Those warnings exist because
	// the walk skips what it cannot read: every other command would otherwise
	// lose a fiber without saying so. `felt check` reports the same failures
	// properly, as counted issues (see CheckParseability), so it turns them off
	// rather than printing each one twice.
	quietWalk bool

	// memoWalk keeps the first store walk and reuses it (see MemoizeWalk);
	// walk is that snapshot, dropped by every write through this Storage.
	memoWalk bool
	walkMu   sync.Mutex
	walk     *storeWalk

	enclosingOnce sync.Once
	external      *ExternalRefs
}

// ErrExternalReference reports a query that names a real fiber in the
// ENCLOSING store rather than this one. It is a resolution failure — the
// fiber is not in this VIEW — but a distinguishable one, and what callers do
// with it differs: `felt check` stays quiet (the link is healthy, the view is
// narrow), while a command acting on user input reaches across and operates
// on the fiber where it lives.
//
// The sentinel exists to stop the basename rescue from stealing foreign paths
// and to tell check "not broken". It is not a fence around the enclosing
// store, and the error text deliberately suggests no command: the caller
// knows which verb the user typed, this package does not.
var ErrExternalReference = errors.New("lives in the enclosing felt store")

// ExternalReference is the resolution failure ErrExternalReference names,
// carrying enough to act on: the query as typed, the id it has in the
// enclosing store, and where that store is.
// Inferred distinguishes the two ways a query reaches out there. False means
// the query named the fiber's path exactly, from the enclosing store's root —
// someone deliberately wrote the full outer id, and there is nothing to
// remark on. True means the enclosing store's own resolver INFERRED the
// target by its scope, suffix, and basename rules; that is the case that can
// quietly outrank a local rescue, and the only one worth reporting.
//
// Guessed narrows Inferred to the inferences that are guesses: the enclosing
// store matched only a tail, a prefix or a last segment of the query, not the
// query itself from the citing fiber's position out there. Commands that
// delete or move refuse a guessed target (see FindMetadataWithoutGuessing).
type ExternalReference struct {
	Query      string
	ID         string
	Root       string // the enclosing .felt directory
	ProjectDir string // its project root — what `felt -C` takes
	Inferred   bool
	Guessed    bool
}

func (e *ExternalReference) Error() string {
	return fmt.Sprintf("%q %s as %s (%s)", e.Query, ErrExternalReference, e.ID, e.Root)
}

func (e *ExternalReference) Unwrap() error { return ErrExternalReference }

// AsExternalReference extracts the external-reference detail from an error,
// for a caller that wants to act on the fiber rather than report the failure.
func AsExternalReference(err error) (*ExternalReference, bool) {
	var ref *ExternalReference
	if errors.As(err, &ref) {
		return ref, true
	}
	return nil, false
}

// EnclosingStore reports the store this one is mounted inside, if any.
//
// A substore is a `.felt/` that is a symlink into a subdirectory of another
// `.felt/` — the project store at `<project>/.felt` pointing into the loom at
// `~/loom/.felt/<prefix>`. root is the enclosing `.felt/` directory, prefix is
// this store's slash-separated position inside it, and ok is false for an
// ordinary top-level store.
//
// s.root is the unresolved path (the symlink itself), so the answer comes
// from EvalSymlinks plus an ancestor walk looking for a `.felt` directory.
// The result is memoized: resolution consults it once per query.
func (s *Storage) EnclosingStore() (root string, prefix string, ok bool) {
	s.enclosingOnce.Do(func() {
		resolved, err := filepath.EvalSymlinks(s.root)
		if err != nil {
			return
		}
		for dir := filepath.Dir(resolved); ; dir = filepath.Dir(dir) {
			if filepath.Base(dir) == DirName && looksLikeStore(dir) {
				rel, err := filepath.Rel(dir, resolved)
				if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
					return
				}
				s.external = &ExternalRefs{root: dir, prefix: filepath.ToSlash(rel), cache: map[string]string{}, via: map[string]resolution{}}
				return
			}
			if parent := filepath.Dir(dir); parent == dir {
				return
			}
		}
	})
	return s.external.Root(), s.external.Prefix(), s.external != nil
}

// ExternalRefs returns the external-reference oracle for this store, or nil
// when the store is top-level (nothing is external to a store that encloses
// nothing). The nil value is usable — every method is nil-safe — so callers
// pass it along without branching. One instance per Storage, so its stat
// answers are memoized across calls.
func (s *Storage) ExternalRefs() *ExternalRefs {
	s.EnclosingStore()
	return s.external
}

// looksLikeStore reports whether dir holds felt content, so that a directory
// that is merely NAMED `.felt` — a repository checked out inside someone
// else's store, a stray fixture — is not mistaken for the store this one is
// mounted in. One ReadDir: a fiber is either a bare `<slug>.md` or a
// `<slug>/<slug>.md`, and one of either is enough.
func looksLikeStore(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() {
			if name != LegacyMystConfigName && strings.HasSuffix(name, FileExt) {
				return true
			}
			continue
		}
		if info, err := os.Stat(filepath.Join(dir, name, name+FileExt)); err == nil && !info.IsDir() {
			return true
		}
	}
	return false
}

// ExternalRefs answers, for a substore, whether a reference target names a
// fiber that lives elsewhere in the enclosing store. Two questions, both of
// which change how a query should be read from inside the substore:
//
//   - Localize: a target written with this store's own prefix
//     (`ai-futures/felt/debug`) is a LOCAL fiber spelled from the outer
//     namespace; strip the prefix and resolve the remainder in-store.
//   - Resolves: a target the ENCLOSING store resolves to a fiber outside this
//     store's prefix is genuinely elsewhere, and must not be salvaged by the
//     basename fallback into whatever local fiber shares its slug.
type ExternalRefs struct {
	root   string
	prefix string

	once     sync.Once
	resolver *scopedIDResolver

	mu    sync.Mutex
	cache map[string]string     // query -> its id out there, "" for "not out there"
	via   map[string]resolution // query -> the rule that found it out there
}

// Root is the enclosing `.felt/` directory.
func (x *ExternalRefs) Root() string {
	if x == nil {
		return ""
	}
	return x.root
}

// Prefix is this store's position inside the enclosing store.
func (x *ExternalRefs) Prefix() string {
	if x == nil {
		return ""
	}
	return x.prefix
}

// ProjectDir is the directory to hand `felt -C` to open the enclosing store.
func (x *ExternalRefs) ProjectDir() string {
	if x == nil {
		return ""
	}
	return filepath.Dir(x.root)
}

// Localize strips this store's own prefix from a query, reporting whether it
// applied.
func (x *ExternalRefs) Localize(query string) (string, bool) {
	if x == nil || x.prefix == "" {
		return query, false
	}
	rest, ok := strings.CutPrefix(query, x.prefix+"/")
	if !ok || rest == "" {
		return query, false
	}
	return rest, true
}

// LookupPath is the cheap half of the external check: query names a fiber in
// the enclosing store when `<root>/<query>/<slug>.md` is there — the canonical
// on-disk shape of a fiber. Two syscalls, memoized, no walk, which is why it
// runs on every miss rather than behind the probe gate.
//
// It answers only for ids written out in full from the enclosing store's root.
// Partial paths and bare slugs that live deeper are the walk's business.
func (x *ExternalRefs) LookupPath(query string) (string, bool) {
	if x == nil || query == "" || strings.HasPrefix(query, "/") || strings.HasPrefix(query, "..") {
		return "", false
	}
	if query == x.prefix || strings.HasPrefix(query, x.prefix+"/") {
		return "", false
	}
	key := "path\x00" + query
	x.mu.Lock()
	id, seen := x.cache[key]
	x.mu.Unlock()
	if seen {
		return id, id != ""
	}

	id = ""
	file := filepath.Join(x.root, filepath.FromSlash(query), path.Base(query)+FileExt)
	if info, err := os.Stat(file); err == nil && !info.IsDir() {
		id = query
	}
	x.mu.Lock()
	x.cache[key] = id
	x.mu.Unlock()
	return id, id != ""
}

// Lookup reports whether the enclosing store resolves query — from the
// position this store's scope occupies out there — to a fiber outside this
// store's own subtree.
//
// The test is resolution, not file existence, because that is how the links
// were written: `[[gotcha-remote-felt-index-stale-after-gitsync]]` and
// `[[portolan/patterns/switch-to-permission-mode-auto]]` name no path from
// the loom root, and both resolve cleanly from the loom by the same slug and
// suffix rules this resolver applies locally. Asking the enclosing store the
// same question the loom's own `felt check` asks is the only predicate that
// agrees with it.
//
// A hit that lands back inside this store's prefix is NOT external — it is a
// local fiber the enclosing store reached by a path this view spells
// differently — so it falls through to the local fallbacks.
//
// The enclosing store's id list is walked once, lazily: nothing here runs
// until a query has already failed to resolve locally, so a top-level store
// or a substore with clean links never pays for it.
func (x *ExternalRefs) Lookup(scopeID, query string) (string, resolution, bool) {
	if x == nil || query == "" {
		return "", resolvedExact, false
	}
	key := scopeID + "\x00" + query
	x.mu.Lock()
	found, seen := x.cache[key]
	via := x.via[key]
	x.mu.Unlock()
	if seen {
		return found, via, found != ""
	}

	x.once.Do(func() {
		outer := &Storage{root: x.root}
		files, err := outer.listFiberFiles()
		if err != nil {
			x.resolver = newScopedIDResolverIn(nil, nil)
			return
		}
		ids := make([]string, 0, len(files))
		for _, file := range files {
			ids = append(ids, file.id)
		}
		x.resolver = newScopedIDResolverIn(ids, nil)
	})

	// The citing fiber sits at <prefix>/<scopeID> in the outer namespace;
	// resolving from there is the same lexical walk the enclosing store runs.
	id, via, err := x.resolver.resolve(path.Join(x.prefix, scopeID), query)
	if err != nil || id == x.prefix || strings.HasPrefix(id, x.prefix+"/") {
		id = ""
	}

	x.mu.Lock()
	x.cache[key] = id
	x.via[key] = via
	x.mu.Unlock()
	return id, via, id != ""
}

// strayAt reports whether query, spelled from the enclosing store's root or
// from the citing fiber's position out there, names a stray fiber file in the
// enclosing store. The returned location is absolute: `.felt/` alone would
// read as this store's.
func (x *ExternalRefs) strayAt(scopeID, query string) (string, bool) {
	if x == nil {
		return "", false
	}
	outer := &Storage{root: x.root}
	candidates := []string{query}
	for _, scope := range scopeChain(path.Join(x.prefix, scopeID)) {
		candidates = append(candidates, scopedQuery(scope, query))
	}
	for _, candidate := range candidates {
		if rel, ok := outer.strayAt(candidate); ok {
			return filepath.Join(x.root, filepath.FromSlash(rel)), true
		}
	}
	return "", false
}

// err builds the resolution failure for an external target: the sentinel, the
// query, and the id it has out there — everything a caller needs to act on
// the fiber where it lives.
func (x *ExternalRefs) err(query, id string, inferred, guessed bool) error {
	return &ExternalReference{Query: query, ID: id, Root: x.root, ProjectDir: x.ProjectDir(), Inferred: inferred, Guessed: guessed}
}

