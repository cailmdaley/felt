// NewStorage creates a storage instance for the given directory.
// The directory should be the project root (containing .felt/).
func NewStorage(projectRoot string) *Storage {
	return &Storage{
		root: filepath.Join(projectRoot, DirName),
	}
}

// Root is this store's `.felt` directory — the path that identifies the store
// a fiber was found in, which a cross-store result has to name.
func (s *Storage) Root() string { return s.root }

// Init creates the .felt directory if it doesn't exist.
func (s *Storage) Init() error {
	if err := os.MkdirAll(s.root, 0755); err != nil {
		return fmt.Errorf("creating .felt directory: %w", err)
	}
	gitignorePath := filepath.Join(s.root, GitignoreName)
	if _, err := os.Stat(gitignorePath); os.IsNotExist(err) {
		if err := os.WriteFile(gitignorePath, []byte(defaultGitignore), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", GitignoreName, err)
		}
	} else if err != nil {
		return fmt.Errorf("checking %s: %w", GitignoreName, err)
	}
	return nil
}

// SilenceWalkWarnings suppresses the listing walk's stderr warnings about
// files it had to skip. Only `felt check` should use it: it reports those same
// files as issues, with an exit code behind them, and printing both would say
// the same thing twice in two different registers.
func (s *Storage) SilenceWalkWarnings() {
	s.quietWalk = true
}

// MemoizeWalk makes the store walk run once and serve every later listing,
// check and layout inspection through this Storage, so a read-only command
// that lists fibers and then inspects the layout — `felt check`, the session
// hook — pays for one walk. A write through this Storage drops the snapshot;
// files changed behind its back are not seen, which is why only read-only
// commands turn it on.
func (s *Storage) MemoizeWalk() {
	s.memoWalk = true
}

// forgetWalk drops the memoized walk after a write.
func (s *Storage) forgetWalk() {
	s.walkMu.Lock()
	s.walk = nil
	s.walkMu.Unlock()
}

// Exists returns true if the .felt directory exists.
func (s *Storage) Exists() bool {
	info, err := os.Stat(s.root)
	return err == nil && info.IsDir()
}

// Path returns the full path for a felt file. Fibers can take one of two
// on-disk shapes:
//
//   - directory form  `<.felt>/<id>/<slug>.md`   (the standard layout)
//   - bare form       `<.felt>/<dir>/<slug>.md`  (no `<slug>/` nesting)
//
// The bare form belongs to namespace roots only: the file sits directly
// inside a `.felt/` rather than in a `<slug>/` subdirectory. At depth zero
// it is the project-root fiber. At depth greater than zero it is the
// entry-point fiber of another store mounted through a symlinked
// subdirectory, which surfaces in the outer namespace one tier deeper than
// the outer root — so for a nested id the bare form is honoured only when
// `<dir>` is that symlink. Anywhere else a bare `.md` is either a companion
// file or a stray fiber (see StrayFibers), and neither is addressable as a
// fiber.
func (s *Storage) Path(id string) string {
	id = filepath.ToSlash(filepath.Clean(id))
	slug := path.Base(id)
	dir := path.Dir(id)
	dirForm := filepath.Join(s.root, filepath.FromSlash(id), slug+FileExt)
	if dir == "." {
		// Top-level: prefer the bare shape `.felt/<slug>.md` when it exists —
		// that's the project-root fiber's canonical layout when this store
		// is mounted into an outer one via a symlink at the parent level.
		// Falls back to the directory form for the standard nested layout.
		bare := filepath.Join(s.root, slug+FileExt)
		if _, err := os.Stat(bare); err == nil {
			return bare
		}
		return dirForm
	}
	// Nested ids: directory form first, so a companion `.md` beside a
	// directory-form fiber can never shadow it.
	if _, err := os.Stat(dirForm); err == nil {
		return dirForm
	}
	mount := filepath.Join(s.root, filepath.FromSlash(dir))
	if info, err := os.Lstat(mount); err == nil && info.Mode()&os.ModeSymlink != 0 {
		bare := filepath.Join(mount, slug+FileExt)
		if _, err := os.Stat(bare); err == nil {
			return bare
		}
	}
	return dirForm
}

// CheckAvailableID returns an error if the target fiber ID already exists.
func (s *Storage) CheckAvailableID(id string) error {
	id = filepath.ToSlash(filepath.Clean(strings.TrimSpace(id)))
	if id == "." || id == "" {
		return fmt.Errorf("invalid felt id")
	}
	if _, err := os.Stat(s.Path(id)); err == nil {
		return fmt.Errorf("fiber %q already exists", id)
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("checking existing fiber %q: %w", id, err)
	}
	if rel, ok := s.strayAt(id); ok {
		return strayHintError(fmt.Errorf("fiber %q would collide with a stray fiber file", id), rel)
	}
	return nil
}

// Write saves a felt to disk.
func (s *Storage) Write(f *Felt) error {
	if f == nil {
		return fmt.Errorf("cannot write nil felt")
	}
	data, err := f.Marshal()
	if err != nil {
		return err
	}

	s.forgetWalk()
	path := s.Path(f.ID)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return fmt.Errorf("creating directory %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, data, 0644); err != nil {
		return fmt.Errorf("writing file %s: %w", path, err)
	}
	return nil
}

// Read loads a felt from disk by ID.
func (s *Storage) Read(id string) (*Felt, error) {
	return s.readPathWithMode(s.Path(id), id, ParseFull)
}

// FindMetadataInScope returns the first felt matching the query using lexical
// scoped resolution rooted at scopeID.
func (s *Storage) FindMetadataInScope(scopeID, query string) (*Felt, error) {
	return s.findWithModeAndScope(scopeID, query, ParseMetadataOnly)
}

// FindMetadataWithoutGuessing is FindMetadataInScope for commands that delete
// or move a fiber: it refuses a guess, returning a *GuessError that names the
// fiber the guess would have reached. A guess is what `felt check` warns on —
// a multi-segment path whose written prefix matched nothing, rescued by its
// last segment — plus an in-scope prefix completion, and, from a substore, any
// answer the enclosing store infers by tail, prefix or last segment rather
// than by the query itself. Everything check accepts silently is accepted: an
// exact id, the lexical scope chain, the view's own prefix, a unique bare slug
// and a correct partial tail.
func (s *Storage) FindMetadataWithoutGuessing(scopeID, query string) (*Felt, error) {
	f, via, err := s.find(scopeID, query, ParseMetadataOnly)
	if ref, ok := AsExternalReference(err); ok && ref.Guessed {
		return nil, &GuessError{Query: query, Guess: ref.ID, Root: ref.Root}
	}
	if err != nil {
		return nil, err
	}
	if via.guess() {
		return nil, &GuessError{Query: query, Guess: f.ID}
	}
	return f, nil
}

// GuessError is a query that only a guess resolves — to Guess, in the
// enclosing store at Root when set (see FindMetadataWithoutGuessing).
type GuessError struct {
	Query string
	Guess string
	Root  string
}

func (e *GuessError) Error() string {
	where := ""
	if e.Root != "" {
		where = fmt.Sprintf(" (in %s)", e.Root)
	}
	return fmt.Sprintf("%q only reaches a fiber by guessing, and this command does not act on a guess; did you mean %s%s?", e.Query, e.Guess, where)
}

// FindExistingMetadataInScope resolves only direct on-disk candidates in the
// lexical scope chain. It intentionally does not fall back to walking the whole
// store, so narrow read paths can annotate exact refs without surprise work.
func (s *Storage) FindExistingMetadataInScope(scopeID, query string) (*Felt, bool, error) {
	return s.findExistingPathWithModeAndScope(scopeID, query, ParseMetadataOnly)
}

// readPathWithMode reads a fiber from a known on-disk path. Used by list-time
// callers that already discovered the file via the walk and shouldn't re-derive
// the path from the id (which loses information when ids cross symlink
// boundaries — e.g. an entry-point bare-form fiber inside a symlinked
// sub-store has no recoverable shape from the prefixed id alone).
func (s *Storage) readPathWithMode(path, id string, mode ParseMode) (*Felt, error) {
	// Canonicalize the on-disk path once so every surface (walk-time list and
	// direct single-read) carries the same absolute, symlink-resolved location
	// — the real "where the bytes are". Walk-time paths are already resolved,
	// so EvalSymlinks is a no-op there; the single-read path is computed via
	// s.Path(id) against the (possibly symlinked) store root, so resolving here
	// keeps it from leaking a symlink-traversing path. Reads still use the
	// original `path` (resolved is only what we carry on f.Path); fall back to
	// the original if resolution fails so a transient stat error can't drop the
	// path entirely.
	carriedPath := path
	if resolved, err := filepath.EvalSymlinks(path); err == nil {
		carriedPath = resolved
	}

	var f *Felt
	if mode == ParseMetadataOnly {
		var err error
		if f, err = readMetadataFile(path, id); err != nil {
			return nil, fmt.Errorf("reading file %s: %w", path, err)
		}
	} else {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("reading file %s: %w", path, err)
		}
		if f, err = ParseWithMode(id, data, mode); err != nil {
			return nil, err
		}
	}
	// Carry the on-disk path so consumers read it instead of
	// reconstructing it from the id.
	f.Path = carriedPath
	return f, nil
}

// Delete removes a felt from disk.
func (s *Storage) Delete(id string) error {
	s.forgetWalk()
	path := s.Path(id)
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("deleting file %s: %w", path, err)
	}
	return s.pruneEmptyDirs(filepath.Dir(path))
}

// pruneEmptyDirs removes now-empty ancestor directories, walking from startDir
// up toward (but never including) the store root. It stops at the first
// non-empty directory; any other removal error is reported.
func (s *Storage) pruneEmptyDirs(startDir string) error {
	for dir := startDir; dir != s.root; dir = filepath.Dir(dir) {
		err := os.Remove(dir)
		if err == nil {
			continue
		}
		if errors.Is(err, syscall.ENOTEMPTY) {
			break
		}
		return fmt.Errorf("cleaning directory %s: %w", dir, err)
	}
	return nil
}

// MoveResult names the fibers whose files a move rewrote, by their ids after
// the move. Outside holds fibers of the enclosing store, outside this view,
// by their ids there.
type MoveResult struct {
	Rewritten []string
	Outside   []string
}

// MoveSubtree moves a fiber and any nested descendants to a new path, rewriting
// the references whose meaning the move would otherwise change.
//
// A reference — body link or inputs.from — is rewritten when its path resolved
// before the move and no longer resolves to the same fiber after it: one left
// pointing at the old path, or one the moved fibers would capture (see
// rewriteMovedRef). When this store is a view into an
// enclosing store, the enclosing store's fibers outside the view are rewritten
// the same way, in its own coordinates: links from other projects are the ones
// a move inside a view would otherwise leave behind. Only files whose content
// changes are written; a moved fiber's id is its location, not its content,
// so the rename alone moves it.
func (s *Storage) MoveSubtree(oldID, newID string) (*MoveResult, error) {
	oldID = filepath.ToSlash(filepath.Clean(strings.TrimSpace(oldID)))
	newID = filepath.ToSlash(filepath.Clean(strings.TrimSpace(newID)))
	if oldID == "." || oldID == "" || newID == "." || newID == "" {
		return nil, fmt.Errorf("invalid felt id")
	}
	if oldID == newID {
		return nil, fmt.Errorf("source and destination are the same")
	}
	if strings.HasPrefix(newID, oldID+"/") {
		return nil, fmt.Errorf("cannot move %s into its own subtree %s", oldID, newID)
	}
	if _, err := os.Stat(s.Path(newID)); err == nil {
		return nil, fmt.Errorf("destination %s already exists", newID)
	} else if !os.IsNotExist(err) {
		return nil, fmt.Errorf("checking destination %s: %w", newID, err)
	}

	felts, err := s.List()
	if err != nil {
		return nil, err
	}
	movedAny := false
	for _, f := range felts {
		if _, ok := remapIDPrefix(f.ID, oldID, newID); ok {
			movedAny = true
			break
		}
	}
	if !movedAny {
		return nil, fmt.Errorf("no fiber found at %s", oldID)
	}

	external := s.ExternalRefs()
	writes, err := planMoveRewrites(felts, felts, external, oldID, newID)
	if err != nil {
		return nil, err
	}
	var outsideWrites []pendingWrite
	if external != nil {
		outsideWrites, err = s.planOutsideRewrites(external, oldID, newID)
		if err != nil {
			return nil, err
		}
	}

	oldRoot := filepath.Join(s.root, filepath.FromSlash(oldID))
	newRoot := filepath.Join(s.root, filepath.FromSlash(newID))
	if _, err := os.Stat(newRoot); err == nil {
		return nil, fmt.Errorf("destination %s already exists", newID)
	} else if !os.IsNotExist(err) {
		return nil, fmt.Errorf("checking destination directory %s: %w", newID, err)
	}
	if err := os.MkdirAll(filepath.Dir(newRoot), 0755); err != nil {
		return nil, fmt.Errorf("creating destination parent %s: %w", filepath.Dir(newRoot), err)
	}
	s.forgetWalk()
	if err := os.Rename(oldRoot, newRoot); err != nil {
		return nil, fmt.Errorf("moving subtree %s -> %s: %w", oldRoot, newRoot, err)
	}

	result := &MoveResult{}
	for _, w := range writes {
		if err := w.write(s); err != nil {
			return result, err
		}
		result.Rewritten = append(result.Rewritten, w.id)
	}
	for _, w := range outsideWrites {
		if err := w.write(s); err != nil {
			return result, err
		}
		result.Outside = append(result.Outside, w.id)
	}
	sort.Strings(result.Rewritten)
	sort.Strings(result.Outside)
	return result, s.pruneEmptyDirs(filepath.Dir(oldRoot))
}

// pendingWrite is a fiber file's new content, planned before the move and
// written after it. path is where the file already is; empty means the fiber
// moved, and its file is found by id once the rename has happened.
type pendingWrite struct {
	id   string
	path string
	data []byte
}

func (w pendingWrite) write(s *Storage) error {
	path := w.path
	if path == "" {
		path = s.Path(w.id)
	}
	if err := os.WriteFile(path, w.data, 0644); err != nil {
		return fmt.Errorf("writing file %s: %w", path, err)
	}
	return nil
}

// planOutsideRewrites plans the rewrites in the enclosing store's fibers
// outside this view. Addresses there are outer ids, so the move is lifted by
// this store's prefix; the outer resolvers see every outer id, the view's
// included, but only the fibers outside it are sources — the view's own were
// planned in its coordinates.
func (s *Storage) planOutsideRewrites(external *ExternalRefs, oldID, newID string) ([]pendingWrite, error) {
	prefix := external.Prefix()
	outer := &Storage{root: external.Root()}
	all, err := outer.List()
	if err != nil {
		return nil, err
	}
	outside := make([]*Felt, 0, len(all))
	for _, f := range all {
		if f.ID != prefix && !strings.HasPrefix(f.ID, prefix+"/") {
			outside = append(outside, f)
		}
	}
	return planMoveRewrites(all, outside, nil, path.Join(prefix, oldID), path.Join(prefix, newID))
}

// planMoveRewrites plans the file rewrites for sources when oldID moves to
// newID within the id space of all.
func planMoveRewrites(all, sources []*Felt, external *ExternalRefs, oldID, newID string) ([]pendingWrite, error) {
	oldIDs := make([]string, 0, len(all))
	newIDs := make([]string, 0, len(all))
	for _, f := range all {
		oldIDs = append(oldIDs, f.ID)
		remapped, _ := remapIDPrefix(f.ID, oldID, newID)
		newIDs = append(newIDs, remapped)
	}
	sort.Strings(oldIDs)
	sort.Strings(newIDs)
	before := newScopedIDResolverIn(oldIDs, external)
	after := newScopedIDResolverIn(newIDs, external)

	var writes []pendingWrite
	for _, f := range sources {
		sourceNew, moved := remapIDPrefix(f.ID, oldID, newID)
		rewrite := func(target string) (string, bool) {
			return rewriteMovedRef(before, after, f.ID, sourceNew, target, oldID, newID)
		}
		clone := *f
		clone.ID = sourceNew
		flowChanged := clone.RewriteDataFlowRefs(func(ref string) (string, bool) {
			target, fragment := splitDataFlowRef(ref)
			next, ok := rewrite(target)
			if !ok {
				return ref, false
			}
			if fragment != "" {
				next += "." + fragment
			}
			return next, true
		})
		body, bodyChanged := RewriteBodyRefs(f.Body, rewrite)
		if !flowChanged && !bodyChanged {
			continue
		}

		var data []byte
		var err error
		if flowChanged {
			// inputs.from lives in frontmatter, so the file is re-rendered.
			clone.Body = body
			data, err = clone.Marshal()
		} else {
			// A body-only change edits the body bytes in place, leaving the
			// frontmatter exactly as its author wrote it.
			data, err = rewriteFileBody(f.Path, rewrite)
		}
		if err != nil {
			return nil, fmt.Errorf("rewriting references in %s: %w", f.ID, err)
		}
		w := pendingWrite{id: sourceNew, path: f.Path, data: data}
		if moved {
			w.path = ""
		}
		writes = append(writes, w)
	}
	return writes, nil
}

// rewriteMovedRef decides one reference's fate when oldID moves to newID. The
// source fiber sits at sourceOld before the move and sourceNew after it.
//
// A reference is rewritten only when its path resolved before the move and
// does not resolve by path to the same fiber after it — the same fiber being
// the one it named, at its new id if it moved. That covers a path into the
// moved subtree that the move leaves behind, and a path to a fiber that stays
// put but that the move would capture: [[x]] naming a/xy by prefix from a/sib
// comes to name a/x once x is nested under a, so it is pinned to a/xy. It
// leaves alone every spelling the move does not change — a bare slug or a
// suffix that still names its fiber uniquely, a scope-relative path that moved
// with its scope — as well as links that already resolved only by the
// basename rescue.
//
// The new spelling keeps the reference's shape where it can: a path written
// relative to a scope stays relative to that scope, and one written from the
// enclosing store's namespace stays in it. Failing that, it is the full id.
func rewriteMovedRef(before, after *scopedIDResolver, sourceOld, sourceNew, target, oldID, newID string) (string, bool) {
	target = cleanLookupQuery(target)
	resolved, ok := before.ResolvePath(sourceOld, target)
	if !ok {
		return "", false
	}
	destination, _ := remapIDPrefix(resolved, oldID, newID)
	if got, ok := after.ResolvePath(sourceNew, target); ok && got == destination {
		return "", false
	}

	var candidates []string
	if anchor, ok := strings.CutSuffix(resolved, "/"+target); ok {
		if rest, ok := strings.CutPrefix(destination, anchor+"/"); ok {
			candidates = append(candidates, rest)
		}
	} else if prefix := after.external.Prefix(); prefix != "" && target == prefix+"/"+resolved {
		candidates = append(candidates, prefix+"/"+destination)
	}
	for _, candidate := range candidates {
		if got, ok := after.ResolvePath(sourceNew, candidate); ok && got == destination {
			return candidate, true
		}
	}
	return destination, true
}

// rewriteFileBody applies rewrite to the body references of the fiber file at
// path, returning the file's new bytes with its frontmatter untouched.
func rewriteFileBody(path string, rewrite func(string) (string, bool)) ([]byte, error) {
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	_, _, bodyStart, err := frontmatterBounds(content)
	if err != nil {
		return nil, err
	}
	body, _ := RewriteBodyRefs(string(content[bodyStart:]), rewrite)
	out := make([]byte, 0, bodyStart+len(body))
	out = append(out, content[:bodyStart]...)
	return append(out, body...), nil
}

// Migrate performs the storage-model normalization pass:
// flat-file fibers become directory fibers, stray fiber files fold into the
// directory layout, legacy frontmatter `title` fields become `name`, and
// leading MyST anchor lines are stripped from bodies.
func (s *Storage) Migrate(dryRun bool) (*MigrationResult, error) {
	result, err := s.MigrateFlatFiles(dryRun)
	if err != nil {
		return nil, err
	}

	if result.Strays, err = s.StrayFibers(); err != nil {
		return nil, err
	}
	if !dryRun {
		// A fold that fails is reported like a blocked one and the pass goes
		// on: the folds before it are done, and stopping here would hide them
		// and skip the normalization below.
		for i := range result.Strays {
			sf := &result.Strays[i]
			if sf.Blocked != "" {
				continue
			}
			if err := sf.fold(); err != nil {
				sf.Blocked = err.Error()
			}
		}
		s.forgetWalk()
	}

	if err := s.normalizeFiberFiles(dryRun, result); err != nil {
		return nil, err
	}
	return result, nil
}

// MigrateFlatFiles converts legacy top-level flat markdown fibers to
// directory-based fibers with slug IDs, rewriting data-flow references.
func (s *Storage) MigrateFlatFiles(dryRun bool) (*MigrationResult, error) {
	if err := s.Init(); err != nil {
		return nil, err
	}

	entries, err := os.ReadDir(s.root)
	if err != nil {
		return nil, fmt.Errorf("reading .felt directory: %w", err)
	}

	type legacyFiber struct {
		oldID string
		path  string
		felt  *Felt
	}

	var legacy []legacyFiber
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if name == LegacyMystConfigName || filepath.Ext(name) != FileExt {
			continue
		}
		oldID := strings.TrimSuffix(name, FileExt)
		data, err := os.ReadFile(filepath.Join(s.root, name))
		if err != nil {
			return nil, fmt.Errorf("reading legacy fiber %s: %w", name, err)
		}
		f, err := Parse(oldID, data)
		if err != nil {
			return nil, fmt.Errorf("parsing legacy fiber %s: %w", name, err)
		}
		legacy = append(legacy, legacyFiber{
			oldID: oldID,
			path:  filepath.Join(s.root, name),
			felt:  f,
		})
	}

	// Exactly one bare root .md is assumed the entry-point fiber and left
	// untouched; with two or more we can't tell entry-point from stray, so all
	// are migrated (to <slug>/<slug>.md form).
	if len(legacy) == 1 {
		return &MigrationResult{}, nil
	}

	result := &MigrationResult{Entries: make([]MigrationEntry, 0, len(legacy))}
	if len(legacy) == 0 {
		return result, nil
	}

	used := map[string]struct{}{}
	for _, f := range legacy {
		baseID, err := GenerateID(f.felt.DisplayName())
		if err != nil {
			return nil, fmt.Errorf("generate slug for %s: %w", f.oldID, err)
		}
		newID, err := s.nextAvailableMigrationID(baseID, used)
		if err != nil {
			return nil, err
		}
		used[newID] = struct{}{}
		result.Entries = append(result.Entries, MigrationEntry{
			OldID: f.oldID,
			NewID: newID,
		})
	}

	slices.SortFunc(result.Entries, func(a, b MigrationEntry) int {
		return strings.Compare(a.OldID, b.OldID)
	})

	if dryRun {
		return result, nil
	}

	idMap := map[string]string{}
	for _, entry := range result.Entries {
		idMap[entry.OldID] = entry.NewID
	}
	remap := func(ref string) (string, bool) {
		targetFiber, fragment := splitDataFlowRef(ref)
		newID, ok := idMap[targetFiber]
		if !ok {
			return "", false
		}
		if fragment == "" {
			return newID, true
		}
		return newID + "." + fragment, true
	}

	for _, item := range legacy {
		f := item.felt
		f.ID = idMap[item.oldID]
		f.RewriteDataFlowRefs(func(ref string) (string, bool) {
			if remappedFrom, ok := remapDataFlowRef(ref, item.oldID, f.ID); ok {
				return remappedFrom, true
			}
			return remap(ref)
		})
		if err := s.Write(f); err != nil {
			return nil, err
		}
	}

	for _, item := range legacy {
		if err := os.Remove(item.path); err != nil {
			return nil, fmt.Errorf("removing legacy fiber %s: %w", item.path, err)
		}
	}

	// Rewrite stale hex-suffixed data-flow refs in pre-existing directory fibers.
	allFibers, err := s.List()
	if err != nil {
		return nil, fmt.Errorf("listing fibers for input rewrite: %w", err)
	}
	for _, f := range allFibers {
		changed := f.RewriteDataFlowRefs(remap)
		if changed {
			if err := s.Write(f); err != nil {
				return nil, fmt.Errorf("rewriting inputs in %s: %w", f.ID, err)
			}
		}
	}

	return result, nil
}

// normalizeFiberFiles rewrites legacy per-file format details in-place:
// frontmatter `title` -> `name`, and leading MyST anchor lines in bodies.
func (s *Storage) normalizeFiberFiles(dryRun bool, result *MigrationResult) error {
	files, err := s.listFiberFiles()
	if err != nil {
		return err
	}

	for _, file := range files {
		data, err := os.ReadFile(file.path)
		if err != nil {
			return fmt.Errorf("reading fiber %s: %w", file.path, err)
		}

		rewritten, renamedTitle, removedDependsOn, strippedAnchor, err := normalizeFiberFile(file.id, data)
		if err != nil {
			return fmt.Errorf("normalize fiber %s: %w", file.path, err)
		}
		if !renamedTitle && !removedDependsOn && !strippedAnchor {
			continue
		}
		if renamedTitle {
			result.TitleToNameIDs = append(result.TitleToNameIDs, file.id)
		}
		if removedDependsOn {
			result.RemovedDependsOnIDs = append(result.RemovedDependsOnIDs, file.id)
		}
		if strippedAnchor {
			result.StrippedMystAnchorIDs = append(result.StrippedMystAnchorIDs, file.id)
		}
		if dryRun {
			continue
		}
		if err := os.WriteFile(file.path, rewritten, 0644); err != nil {
			return fmt.Errorf("writing normalized fiber %s: %w", file.path, err)
		}
	}

	slices.Sort(result.TitleToNameIDs)
	slices.Sort(result.RemovedDependsOnIDs)
	slices.Sort(result.StrippedMystAnchorIDs)
	return nil
}

// BackfillIntrinsicIDs assigns an intrinsic ULID to every fiber missing one.
// This is intentionally separate from Migrate: replicas must not run it
// casually, or the same git-synced fiber can split into multiple identities.
func (s *Storage) BackfillIntrinsicIDs(dryRun bool) (*IdentityBackfillResult, error) {
	files, err := s.listFiberFiles()
	if err != nil {
		return nil, err
	}

	result := &IdentityBackfillResult{}
	for _, file := range files {
		data, err := os.ReadFile(file.path)
		if err != nil {
			return nil, fmt.Errorf("reading fiber %s: %w", file.path, err)
		}
		rewritten, changed, err := backfillIntrinsicID(data)
		if err != nil {
			fmt.Fprintf(os.Stderr, "warning: failed to backfill %s: %v\n", file.path, err)
			continue
		}
		if !changed {
			continue
		}
		result.AssignedIDs = append(result.AssignedIDs, file.id)
		if dryRun {
			continue
		}
		if err := os.WriteFile(file.path, rewritten, 0644); err != nil {
			return nil, fmt.Errorf("writing identity-backfilled fiber %s: %w", file.path, err)
		}
	}

	slices.Sort(result.AssignedIDs)
	return result, nil
}

func normalizeFiberFile(id string, content []byte) ([]byte, bool, bool, bool, error) {
	frontmatter, body, err := SplitFrontmatter(content, true)
	if err != nil {
		return nil, false, false, false, err
	}

	rewrittenFrontmatter, renamedTitle, removedDependsOn, err := normalizeLegacyFrontmatter(frontmatter)
	if err != nil {
		return nil, false, false, false, err
	}
	rewrittenBody, strippedAnchor := stripLegacyMystAnchor(id, body)
	if !renamedTitle && !removedDependsOn && !strippedAnchor {
		return content, false, false, false, nil
	}

	var out bytes.Buffer
	out.WriteString("---\n")
	out.Write(rewrittenFrontmatter)
	out.WriteString("---\n")
	if rewrittenBody != "" {
		out.WriteString("\n")
		out.WriteString(rewrittenBody)
		if !strings.HasSuffix(rewrittenBody, "\n") {
			out.WriteString("\n")
		}
	}
	return out.Bytes(), renamedTitle, removedDependsOn, strippedAnchor, nil
}

func backfillIntrinsicID(content []byte) ([]byte, bool, error) {
	frontmatter, body, err := SplitFrontmatter(content, true)
	if err != nil {
		return nil, false, err
	}

	rewrittenFrontmatter, changed, err := backfillIntrinsicIDFrontmatter(frontmatter)
	if err != nil {
		return nil, false, err
	}
	if !changed {
		return content, false, nil
	}

	var out bytes.Buffer
	out.WriteString("---\n")
	out.Write(rewrittenFrontmatter)
	out.WriteString("---\n")
	if body != "" {
		out.WriteString(body)
	}
	return out.Bytes(), true, nil
}

func backfillIntrinsicIDFrontmatter(frontmatter []byte) ([]byte, bool, error) {
	mapping, err := frontmatterMappingNode(frontmatter)
	if err != nil {
		return nil, false, err
	}
	if mapping == nil {
		return frontmatter, false, nil
	}

	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == "id" && strings.TrimSpace(mapping.Content[i+1].Value) != "" {
			return frontmatter, false, nil
		}
	}

	idKey := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "id"}
	idValue := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: NewULID()}
	mapping.Content = append([]*yaml.Node{idKey, idValue}, mapping.Content...)

	rewritten, err := yaml.Marshal(mapping)
	if err != nil {
		return nil, false, fmt.Errorf("marshaling YAML frontmatter: %w", err)
	}
	return rewritten, true, nil
}

