import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

export function registerSidebarTreeJourneys(test) {
  test('Sidebar tree remembers folds, keeps current pages visible and flattens Find', async p => {
    const url = `${pathToFileURL(resolve('harness-board-dist/index.html')).href}?example=sidebar-tree`
    await p.goto(url)
    const desk = p.locator('.kbn-desk')
    for (const id of ['chair', 'hub']) assert.equal(await desk.locator(`.kbn-card[data-fiber-id="${id}"]`).count(), 1, 'working seats stay on Desk')
    await desk.locator('.kbn-card[data-fiber-id="chair"]').click()
    const sidebar = p.locator('.ws-sidebar')
    if (!await sidebar.isVisible()) await p.keyboard.press('Meta+[')
    const row = id => sidebar.locator(`.ws-channel-row[data-channel-uid="${id}"]`)
    assert.equal(await row('chair').count(), 1)
    assert.equal(await row('hub').count(), 1)
    assert.equal(await row('chair/question').count(), 1)
    assert.equal(await row('chair/review-2').count(), 0)
    const dotEdge = id => row(id).locator('.kbn-card-header > :first-child').evaluate(el => el.getBoundingClientRect().left)
    assert.equal(await dotEdge('chair'), await dotEdge('hub'), 'a caret does not move a root off the shared edge')
    assert.ok(await dotEdge('chair/question') > await dotEdge('chair'), 'only depth indents a row')
    assert.equal(await row('chair/analysis').count(), 0)
    const beforeHidingDesk = await sidebar.screenshot()
    await desk.evaluate(el => el.style.visibility = 'hidden')
    assert.ok(beforeHidingDesk.equals(await sidebar.screenshot()), 'the Desk cannot bleed blurred patches through the sidebar')
    await desk.evaluate(el => el.style.visibility = '')
    const captions = await sidebar.locator('.kbn-flight-caption').allTextContents()
    assert.equal(new Set(captions).size, captions.length, 'each caption appears once')
    assert.deepEqual(captions, ['Your turn', 'Working', 'Roles', 'Resting'])
    const strip = () => p.locator('.ws-sidebar-index-entry').evaluateAll(els => els.map(el => el.getAttribute('aria-label')))
    const counts = await strip()
    const fold = row('chair').getByRole('button', { name: 'Collapse CMB cross-correlations chair', exact: true })
    await fold.click()
    assert.equal(await row('chair/question').count(), 0)
    assert.ok((await row('chair').textContent()).includes('6 need you'))
    await p.keyboard.press('j')
    assert.equal(await row('hub').getAttribute('aria-current'), 'true', 'j skips the folded family')
    assert.deepEqual(await strip(), counts, 'folds do not change root counts')
    await p.keyboard.press('k')
    assert.equal(await row('chair').getAttribute('aria-current'), 'true')
    await p.reload()
    await row('chair').waitFor()
    assert.equal(await row('chair/question').count(), 0, 'root fold persists')
    await row('chair').getByRole('button', { name: 'Expand CMB cross-correlations chair', exact: true }).click()
    await sidebar.getByRole('button', { name: '+3 more', exact: true }).first().click()
    await sidebar.getByRole('button', { name: 'Working 2', exact: true }).first().click()
    assert.equal(await row('chair/review-4').count(), 1)
    assert.equal(await row('chair/analysis/deep').getAttribute('aria-level'), '3')
    assert.equal(await row('chair/analysis/deep').locator('.ws-sidebar-crumb').count(), 0, 'drawn parent supplies context')
    assert.deepEqual(await strip(), counts, 'More and Working do not change root counts')
    await p.reload()
    await row('chair/analysis/deep').waitFor()
    assert.equal(await row('chair/review-4').count(), 1, 'more and working folds persist')
    await row('chair/analysis/deep').click()
    await row('chair').getByRole('button', { name: 'Collapse CMB cross-correlations chair', exact: true }).click()
    assert.equal(await row('chair/analysis/deep').getAttribute('aria-current'), 'true', 'current page survives a folded root')
    const saved = await p.evaluate(() => localStorage.getItem('shuttle.sidebar.tree'))
    await p.keyboard.press('/')
    await p.locator('input:focus').fill('Response analysis')
    assert.equal(await row('chair/analysis/deep').count(), 1, 'Find searches intermediate parent names')
    assert.match(await row('chair/analysis/deep').locator('.ws-sidebar-crumb').textContent(), /CMB cross-correlations chair.*Response analysis/, 'flat Find results retain their full parent context')
    assert.equal(await p.evaluate(() => localStorage.getItem('shuttle.sidebar.tree')), saved, 'revealing Find does not change preferences')
    await row('chair/analysis').click()
    await p.keyboard.press('j')
    assert.equal(await row('chair/analysis/deep').getAttribute('aria-current'), 'true', 'j walks matches, not hidden rows')
    await p.keyboard.press('/')
    await p.locator('input:focus').fill('Draft archive inventory')
    assert.equal(await row('quiet/draft').count(), 1, 'Find includes threads of Desk-less families')
  }, undefined, 'true')
}
