import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

/** Retain upstream license and notice text for the diff renderer's locked dependency tree. */
export function changeNotices() {
  const modules = fileURLToPath(new URL('../node_modules/', import.meta.url)), seen = new Set(), entries = []
  function visit(name) {
    if (seen.has(name) || name.startsWith('@types/')) return
    seen.add(name)
    const dir = `${modules}/${name}`, pkg = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'))
    const files = readdirSync(dir).filter(file => /^(?:licen[cs]e|notice)(?:\.|$)/i.test(file))
    const texts = files.map(file => `${file}\n\n${readFileSync(`${dir}/${file}`, 'utf8').trim()}`)
    if (name === 'lru_map') texts.push(readFileSync(`${dir}/README.md`, 'utf8').split('# MIT license')[1].trim())
    if (!texts.length) throw new Error(`No license text found for ${name}`)
    entries.push(`${name} ${pkg.version} (${pkg.license})\n${'='.repeat(72)}\n\n${texts.join('\n\n')}`)
    for (const dependency of Object.keys(pkg.dependencies ?? {}).sort()) visit(dependency)
  }
  visit('@pierre/diffs')
  visit('dompurify')
  return `Change reader third-party licenses and notices\n\nGenerated by ui/scripts/change-notices.mjs from the installed lockfile dependencies.\nTheme catalogs are excluded from the reader build; their upstream notices are retained here.\n\n${entries.join('\n\n' + '-'.repeat(72) + '\n\n')}\n`
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../public/change-reader-NOTICES.txt', import.meta.url), changeNotices())
}
